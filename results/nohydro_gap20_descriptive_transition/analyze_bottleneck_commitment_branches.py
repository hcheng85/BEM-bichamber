#!/usr/bin/env python3
"""Analyze paired stochastic restart interventions for a bichamber school.

This is an ANALYSIS module; it does not pretend to restart the production
simulator. `--self-test` generates artificial branch outputs and checks the
pipeline. Real outputs must be generated by an audited simulator adapter.

Input is a single CSV with columns:
  phase          `pre` (first entry) or `post` (continued net transport)
  sample_id      stable frozen microscopic state identifier
  seed           original independent trajectory seed
  clone          independent noise-stream ID shared among treatment arms
  arm            pre: `baseline`, `toward`, `away`;
                 post: `full`, `crossgap_off` (optional if audit supports)
  source_sign    +1 if initially RIGHT-majority, -1 if LEFT-majority
  nright0        initial number in right chamber, after first crossing for post
  nrightT        number in right chamber at the follow-up horizon
  first_entry    1 if a source->minority crossing occurs during the pre horizon
  a_initial      actual majority COM-to-gap polarization after intervention
  a_baseline     same original pre-intervention polarization in all arms

Direction-aligned additional net count is `-source_sign*(nrightT-nright0)`;
post successes are >= 4 additional net fish, excluding first crossing.
Pre successes are first_entry events, NOT net population difference.

No distinction between statistical and causal effects is made without the
simulator audit and paired-common-random-number setup described in README.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

PHASE_ARMS = {'pre': ('baseline', 'toward', 'away'),
              'post': ('full', 'crossgap_off')}
MAIN_BASE = {'pre': 'baseline', 'post': 'full'}
COMPARE = {'pre': ('toward', 'away'), 'post': ('crossgap_off',)}
FIELDS = ('phase','sample_id','seed','clone','arm','source_sign',
          'nright0','nrightT','first_entry','a_initial','a_baseline')


def read_csv(path):
    with open(path, newline='') as f:
        return list(csv.DictReader(f))


def write_csv(path, rows):
    if not rows:
        return
    with open(path, 'w', newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(dict.fromkeys(k for row in rows for k in row)),lineterminator='\n')
        w.writeheader(); w.writerows(rows)


def parse_validate(rows, nfish=100, post_threshold=4):
    """Check pairing, membership parity, and exact endpoint accounting."""
    if not rows: raise ValueError('Empty input')
    out=[];index={};meta={}
    for r in rows:
        for f in FIELDS:
            if f not in r: raise ValueError(f'Missing column {f}')
        phase=r['phase'];arm=r['arm'];sid=r['sample_id'];seed=int(r['seed'])
        if phase not in PHASE_ARMS or arm not in PHASE_ARMS[phase]:
            raise ValueError(f'Unexpected phase/arm: {phase}/{arm}')
        clone=int(r['clone']);sign=int(r['source_sign']);nr0=int(r['nright0']);nrT=int(r['nrightT']);
        if sign not in (-1,1) or not (0<=nr0<=nfish and 0<=nrT<=nfish):
            raise ValueError('Invalid source sign or chamber population count')
        if phase=='pre' and sign*(2*nr0-nfish)<=0:
            raise ValueError(f'Pre origin must have source majority, got {sid} / {arm}')
        entry=int(r['first_entry']);
        if entry not in (0,1):raise ValueError('first_entry must be 0 or 1')
        a=float(r['a_initial']);base_a=float(r['a_baseline'])
        if not(-1.0000001<=a<=1.0000001 and -1.0000001<=base_a<=1.0000001):
            raise ValueError('Invalid polarization')
        key=(phase,sid,clone,arm)
        if key in index:raise ValueError(f'Duplicate paired trial {key}')
        mkey=(phase,sid)
        if mkey in meta:
            prev=meta[mkey]
            if prev['seed']!=seed or prev['sign']!=sign or prev['nr0']!=nr0 or abs(prev['a_base']-base_a)>1e-10:
                raise ValueError(f'Intervention arms do not share frozen state {mkey}')
        else:
            meta[mkey]=dict(seed=seed,sign=sign,nr0=nr0,a_base=base_a)
        # Correctly align to original SOURCE majority, even if q crosses zero.
        additional_net=-sign*(nrT-nr0)
        success=entry if phase=='pre' else int(additional_net>=post_threshold)
        d=dict(phase=phase,sample_id=sid,seed=seed,clone=clone,arm=arm,
               source_sign=sign,nright0=nr0,nrightT=nrT,first_entry=entry,
               a_initial=a,a_baseline=base_a,additional_net=additional_net,
               success=success)
        index[key]=d;out.append(d)
    for (phase,sid),m in meta.items():
        clones=sorted({d['clone'] for d in out if d['phase']==phase and d['sample_id']==sid})
        present={d['arm'] for d in out if d['phase']==phase and d['sample_id']==sid}
        expected=tuple(arm for arm in PHASE_ARMS[phase] if arm in present)
        if phase=='pre' and present != set(PHASE_ARMS[phase]):
            raise ValueError('Pre-entry intervention requires all three arms')
        if phase=='post' and not present.issuperset({'full'}):
            raise ValueError('Post-entry baseline full arm is required')
        for clone in clones:
            missing=[arm for arm in expected
                     if (phase,sid,clone,arm) not in index]
            if missing:raise ValueError(f'Incomplete common-noise pair: {phase}/{sid}/{clone}: {missing}')
        for clone in clones:
            base=index[(phase,sid,clone,MAIN_BASE[phase])]
            if abs(base['a_initial']-base['a_baseline'])>1e-9:
                raise ValueError(f'Baseline polarization mismatch for {phase}/{sid}/{clone}')
        if phase=='pre':
            for clone in clones:
                b=index[('pre',sid,clone,'baseline')]['a_initial']
                to=index[('pre',sid,clone,'toward')]['a_initial']
                away=index[('pre',sid,clone,'away')]['a_initial']
                if to < b-1e-8 or away > b+1e-8:
                    raise ValueError(f'Heading nudge did not monotonically change a: {sid}/{clone}')
    return out,index,meta


def sample_rows(index, meta):
    rows=[]
    for (phase,sid),info in sorted(meta.items()):
        ids=sorted({key[2] for key in index if key[0]==phase and key[1]==sid})
        available=tuple(arm for arm in PHASE_ARMS[phase] if (phase,sid,ids[0],arm) in index)
        data={arm:[index[(phase,sid,k,arm)] for k in ids] for arm in available}
        base=MAIN_BASE[phase]
        rec=dict(phase=phase,sample_id=sid,seed=info['seed'],source_sign=info['sign'],
                 n_clones=len(ids),a_baseline=info['a_base'],nright0=info['nr0'])
        for arm,part in data.items():
            rec[f'p_{arm}']=float(np.mean([r['success'] for r in part]))
            rec[f'net_{arm}']=float(np.mean([r['additional_net'] for r in part]))
            rec[f'a_{arm}']=float(np.mean([r['a_initial'] for r in part]))
        for arm in COMPARE[phase]:
            if arm not in available: continue
            rec[f'da_{arm}_minus_{base}']=rec[f'a_{arm}']-rec[f'a_{base}']
            rec[f'dp_{arm}_minus_{base}']=rec[f'p_{arm}']-rec[f'p_{base}']
            rec[f'dnet_{arm}_minus_{base}']=rec[f'net_{arm}']-rec[f'net_{base}']
            concordant=sum(index[(phase,sid,k,arm)]['success']==index[(phase,sid,k,base)]['success'] for k in ids)
            rec[f'paired_outcome_agreement_{arm}']=concordant/len(ids)
        rows.append(rec)
    return rows


def seed_equal_estimate(srows, phase, key, nboot=10000, seed=20261113):
    byseed=defaultdict(list)
    for row in srows:
        if row['phase']==phase:byseed[int(row['seed'])].append(float(row[key]))
    if not byseed:return dict(available=False)
    vals=np.array([np.mean(byseed[s]) for s in sorted(byseed)])
    rng=np.random.default_rng(seed)
    boot=np.mean(vals[rng.integers(0,len(vals),(nboot,len(vals)))],axis=1)
    ci=np.quantile(boot,[.025,.975]).tolist()
    return dict(available=True,mean=float(np.mean(vals)),ci95=ci,n_seeds=len(vals),
                n_samples=sum(map(len,byseed.values())),
                n_positive_seed_means=int(np.sum(vals>0)),
                n_negative_seed_means=int(np.sum(vals<0)))


def summarize(samples, rows, nboot=10000):
    results={}
    for phase in ('pre','post'):
        part=[r for r in samples if r['phase']==phase]
        if not part:continue
        base=MAIN_BASE[phase]
        d=dict(n_trials=sum(r['n_clones'] for r in part),n_samples=len(part),
               n_seeds=len({r['seed'] for r in part}),
               baseline_success=seed_equal_estimate(samples,phase,f'p_{base}',nboot),
               baseline_additional_net=seed_equal_estimate(samples,phase,f'net_{base}',nboot))
        for arm in COMPARE[phase]:
            if not all(f'dp_{arm}_minus_{base}' in row for row in part):
                d[arm]={'available':False,'reason':'Cross-chamber coupling audit absent/zero: no intervention performed'}
                continue
            d[arm]={
                'success_difference':seed_equal_estimate(samples,phase,f'dp_{arm}_minus_{base}',nboot),
                'additional_net_difference':seed_equal_estimate(samples,phase,f'dnet_{arm}_minus_{base}',nboot),
                'polarization_change':seed_equal_estimate(samples,phase,f'da_{arm}_minus_{base}',nboot),
            }
        results[phase]=d
    results['definitions']={
        'pre_success':'At least one original-majority to minority first crossing within pre horizon; based on native crossing log, NOT net count',
        'post_success':'At least four ADDITIONAL net fish move from the pre-entry source into target after first crossing within post horizon',
        'post_delta_n':'-source_sign*(nrightT-nright0), where nright0 is AFTER the initial first-crossing step',
        'independent_unit':'Original trajectory seed; paired clones and microscopic snapshots are nested, NOT independent seeds',
        'causal_claim_requirements':'Correct simulator restart from exactly frozen state, same noise increments across arms, only registered intervention changed',
        'complete_relocation':'Not assessed; short propagation success is not a whole-school committor'}
    return results


def make_figure(samples,out):
    try:import matplotlib.pyplot as plt
    except ImportError:return
    phases=[x for x in ('pre','post') if any(y['phase']==x for y in samples)]
    fig,axs=plt.subplots(1,len(phases),figsize=(6*len(phases),4),squeeze=False)
    for ax,phase in zip(axs[0],phases):
        part=[r for r in samples if r['phase']==phase]
        arms=tuple(a for a in PHASE_ARMS[phase] if all(f'p_{a}' in r for r in part))
        arrays=[[r[f'p_{a}'] for r in part] for a in arms]
        ax.boxplot(arrays,tick_labels=list(arms),showmeans=True)
        ax.set_ylim(-.03,1.03);ax.set_ylabel('Branch success probability');ax.set_title(
            'Pre-entry crossing' if phase=='pre' else 'Post-entry continued transfer')
        for j in range(1,len(arms)):
            x=np.arange(len(part));a=np.array(arrays[0]);b=np.array(arrays[j]);
            # Connect matched per-state means lightly; no independent-fish claims.
            for k in range(min(len(part),100)):
                ax.plot([1,j+1],[a[k],b[k]],color='0.75',alpha=.18,lw=.7,zorder=0)
    fig.tight_layout();fig.savefig(out,dpi=170);plt.close(fig)


def report(summary):
    lines=['# Microscopic branching test: geometric gating and collective propagation','',
           'This report summarizes *controlled stochastic restarts* when the branch generator follows the companion protocol. The analyzer alone does not verify simulator fidelity.','']
    for phase,label in [('pre','Stage I — first entry'),('post','Stage II — continued transfer')]:
        if phase not in summary:continue
        s=summary[phase];base=MAIN_BASE[phase]
        lines +=[f'## {label}',f"{s['n_samples']} microscopic snapshots from {s['n_seeds']} original seeds; {s['n_trials']} paired noise-stream IDs.",
                 f"Baseline success: {s['baseline_success']['mean']:.5f} (seed CI {s['baseline_success']['ci95']}).",'']
        for arm in COMPARE[phase]:
            if not s[arm].get('available',True):
                lines += [f'- {arm}: not run (structural cross-gap coupling absent or audit unavailable).']
                continue
            d=s[arm]['success_difference'];n=s[arm]['additional_net_difference']
            lines +=[f"- {arm} minus {base}: ΔP={d['mean']:+.5f}, CI {d['ci95']}; Δnet fish={n['mean']:+.5f}, CI {n['ci95']}."]
        lines +=['']
    lines += ['## Interpretation','',
              'Intervention differences are descriptive unless the production restart reproduces the original microscopic rules (except surgical treatment), and cloned arms use the same noise increments. A null cross-gap result cannot distinguish biological absence of communication from implementation errors without a torque-difference audit. A positive heading-nudge result demonstrates response to an imposed cue; it does not identify which native torque generated spontaneous heading changes.','',
              'Do not use 4-fish propagation as the complete opposite-chamber committor; the latter requires separate basin-hitting trajectories.']
    return '\n'.join(lines)+'\n'


def synthetic(path):
    rng=np.random.default_rng(12);rows=[]
    for phase in ('pre','post'):
        for seed in range(8):
            for k in range(2):
                sid=f'{phase}_seed{seed}_{k}';sign=1 if seed%2 else -1
                nr0=75 if sign==1 else 25
                a0=.1+0.02*k
                for clone in range(24):
                    # Common-random-number pairing creates physically meaningful contrasts.
                    u=rng.random()
                    for arm in PHASE_ARMS[phase]:
                        if phase=='pre':
                            prob={'baseline':.3,'toward':.55,'away':.12}[arm]
                            success=int(u<prob)
                            nrt=nr0-sign*success
                            a=a0+{'baseline':0,'toward':.10,'away':-.10}[arm]
                            first_entry=success
                        else:
                            prob={'full':.6,'crossgap_off':.25}[arm]
                            success=int(u<prob)
                            nrt=nr0-sign*(5 if success else 1)
                            a=a0;first_entry=1
                        rows.append(dict(phase=phase,sample_id=sid,seed=seed,clone=clone,arm=arm,
                                         source_sign=sign,nright0=nr0,nrightT=nrt,
                                         first_entry=first_entry,a_initial=a,a_baseline=a0))
    write_csv(path,rows)
    return rows


def main():
    p=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--branches',type=Path,help='CSV of paired stochastic restarted trials')
    p.add_argument('--output',type=Path,default=Path('outputs/bottleneck_commitment_branches'))
    p.add_argument('--bootstrap',type=int,default=5000)
    p.add_argument('--self-test',action='store_true')
    args=p.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    if args.self_test:
        raw=synthetic(args.output/'synthetic_branches.csv')
    else:
        if args.branches is None:p.error('--branches is required unless --self-test')
        raw=read_csv(args.branches)
    validated,index,meta=parse_validate(raw)
    samples=sample_rows(index,meta)
    summary=summarize(samples,validated,args.bootstrap)
    write_csv(args.output/'per_microstate.csv',samples)
    with open(args.output/'summary.json','w') as f:json.dump(summary,f,indent=2)
    (args.output/'REPORT.md').write_text(report(summary))
    make_figure(samples,args.output/'branch_commitment_comparison.png')
    if args.self_test:
        if summary['pre']['toward']['success_difference']['mean']<.1 or summary['pre']['away']['success_difference']['mean']>-.05:
            raise AssertionError('Artificial pre-entry effect missed')
        if summary['post']['crossgap_off']['success_difference']['mean']>-.1:
            raise AssertionError('Artificial cross-gap effect missed')
        print('Self-test passed. Synthetic effects are NOT real fish-school results.')
    print(json.dumps(summary,indent=2))

if __name__=='__main__':main()
